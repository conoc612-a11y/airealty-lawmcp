const RE = /(?<![\dA-Za-z])(19[5-9]\d|20\d\d)([가-힣]{1,4})(\d{1,7})(?![\d가-힣])/g;

/** 텍스트에서 사건번호를 찾는다. {caseNo, year, code, seq, span:[s,e], court?} */
export function findCaseNumbers(text, now = new Date()) {
  const out = [];
  const maxYear = now.getFullYear() + 1;
  for (const m of String(text || "").matchAll(RE)) {
    const year = +m[1], code = m[2], seq = m[3];
    if (year > maxYear || !CASE_CODES.has(code)) continue;
    const start = m.index, end = start + m[0].length;
    const before = text.slice(Math.max(0, start - 40), start);
    const cm = before.match(/(대법원|헌법재판소|[가-힣]{2,8}(?:고등|지방|가정|행정|특허|회생|군사)법원(?:\s*[가-힣]{1,6}지원)?)\s*(?:[\d.\s]*(?:선고|자))?\s*$/);
    out.push({ caseNo: `${m[1]}${code}${seq}`, year, code, seq, span: [start, end], court: cm ? cm[1] : undefined });
  }
  return out;
}

export const isCaseNo = (s) => { const m = String(s || "").replace(/\s+/g, "").match(/^(19[5-9]\d|20\d\d)([가-힣]{1,4})(\d{1,7})$/); return !!m && CASE_CODES.has(m[2]); };
